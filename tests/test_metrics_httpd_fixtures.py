"""The fixtures of the Rust port metrics-httpd (rust/metrics-httpd/PLAN.md 8.2).

rust/metrics-httpd/fixtures/ holds what the Python endpoint scripts and
CPython produce, generated by rust/metrics-httpd/fixtures/generate.py; the
Rust crate's tests replay them (tests/fixtures.rs, tests/apt_state.rs). The
Rust CI only runs for changes under rust/, so a change to an endpoint
template or role that is not followed by regenerated fixtures is caught
here:

- regenerating gives byte-identical files (with the real ``htpasswd`` when
  it is installed, else the stdlib families only);
- the stdlib families give the same bytes under the hosts' CPython 3.12 and
  3.13 when ``uv`` has them (no download);
- every case where the Rust expectation differs from Python names an
  allowed difference of PLAN.md section 5.2, and none widens access;
- the float fixture has the size PLAN.md D-5 asks for, in files the
  repository's large-file hook accepts.

After a change to an endpoint script: `just metrics-httpd-fixtures`, then
update the Rust side in the same change.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CRATE = ROOT / "rust" / "metrics-httpd"
FIXTURES = CRATE / "fixtures"
GENERATOR = FIXTURES / "generate.py"
REGENERATE = "regenerate with `just metrics-httpd-fixtures` and update the Rust side in the same change"


def load(name: str):
    return json.loads((FIXTURES / name).read_text(encoding="utf-8"))


def plan_items() -> set[str]:
    plan = (CRATE / "PLAN.md").read_text(encoding="utf-8")
    section = plan.split("### 5.2 Allowed differences", 1)[1].split("\n## ", 1)[0]
    return set(re.findall(r"^- \*\*(D-\d+) ", section, flags=re.MULTILINE))


def run_generator(python: list[str], *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [*python, str(GENERATOR), "check", *args],
        capture_output=True,
        text=True,
        timeout=600,
        check=False,
    )


class FixturesMatchThePythonEndpoints(unittest.TestCase):
    def test_regenerating_gives_the_committed_fixtures(self) -> None:
        args = [] if shutil.which("htpasswd") else ["--stdlib-only"]
        result = run_generator([sys.executable], *args)
        self.assertEqual(
            result.returncode, 0, f"{result.stdout}{result.stderr}\n{REGENERATE}"
        )
        if args:
            self.skipTest(
                "htpasswd (apache2-utils) is not installed: only the stdlib families were checked"
            )

    def test_stdlib_families_match_the_hosts_pythons(self) -> None:
        uv = shutil.which("uv")
        checked = []
        for version in ("3.12", "3.13"):
            if (
                uv is None
                or subprocess.run(
                    [uv, "python", "find", "--no-project", version],
                    capture_output=True,
                    check=False,
                ).returncode
                != 0
            ):
                continue
            result = run_generator(
                [
                    uv,
                    "run",
                    "--offline",
                    "--python",
                    version,
                    "--no-project",
                    "python",
                    "-I",
                ],
                "--stdlib-only",
            )
            self.assertEqual(
                result.returncode,
                0,
                f"Python {version}: {result.stdout}{result.stderr}\n{REGENERATE}",
            )
            checked.append(version)
        if not checked:
            self.skipTest("uv has neither CPython 3.12 nor 3.13 installed")


class DifferencesAreNamedAndNarrow(unittest.TestCase):
    def test_every_d_item_exists_in_the_plan(self) -> None:
        items = plan_items()
        self.assertTrue({"D-2", "D-4", "D-6", "D-14"} <= items, items)
        tags: list[str] = []
        for case in load("pyjson.json")["dumps"]:
            tags += [case["d"]] if "d" in case else []
        for case in load("auth.json"):
            tags += list(case.get("d", {}).values())
        for variant in load("http_common.json"):
            tags += [case["d"] for case in variant["cases"] if "d" in case]
        tags += [case["d"] for case in load("script.json")["cases"] if "d" in case]
        tags += [
            case["d"] for case in load("apt_state.json")["http"]["cases"] if "d" in case
        ]
        self.assertTrue(tags)
        for tag in tags:
            self.assertIn(tag, items)

    def test_json_differences_are_refusals(self) -> None:
        for case in load("pyjson.json")["dumps"]:
            if "python" in case and case["rust"] != "same":
                self.assertEqual(case["rust"], "invalid", case["id"])
                self.assertIn("d", case, case["id"])
            if "python" not in case:
                self.assertEqual(case["rust"], "invalid", case["id"])

    def test_auth_differences_never_widen_access(self) -> None:
        for case in load("auth.json"):
            for source in ("vi", "vb"):
                python, rust = case["python"][source], case["rust"][source]
                if python != rust:
                    self.assertEqual(rust, "denied", case["id"])
                    self.assertIn(source, case.get("d", {}), case["id"])
                if rust == "ok":
                    self.assertEqual(python, "ok", case["id"])

    def test_script_differences_are_named(self) -> None:
        # Where Python drops the connection or the plan allows a different
        # answer, the case carries the D item and the Rust expectation;
        # every other case is compared with Python's answer.
        for case in load("script.json")["cases"]:
            if case["status"] is None or case["compare"] == "status":
                self.assertIn("d", case, case["id"])
                self.assertIn("rust_status", case, case["id"])
                if case["status"] is not None:
                    self.assertEqual(case["rust_status"], case["status"], case["id"])
            else:
                self.assertNotIn("d", case, case["id"])
                self.assertIn(case["compare"], ("bytes", "html"), case["id"])

    def test_case_ids_are_unique(self) -> None:
        ids = [case["id"] for case in load("pyjson.json")["dumps"]]
        self.assertEqual(len(ids), len(set(ids)))
        ids = [case["id"] for case in load("auth.json")]
        self.assertEqual(len(ids), len(set(ids)))
        for variant in load("http_common.json"):
            ids = [case["id"] for case in variant["cases"]]
            self.assertEqual(len(ids), len(set(ids)), variant["variant"])
        ids = [case["id"] for case in load("script.json")["cases"]]
        self.assertEqual(len(ids), len(set(ids)))
        apt_state = load("apt_state.json")
        for family in (apt_state["reboot_state"], apt_state["http"]["cases"]):
            ids = [case["id"] for case in family]
            self.assertEqual(len(ids), len(set(ids)))

    def test_apt_state_differences_are_named_error_answers(self) -> None:
        # PLAN.md 4.5: Rust differs from the os_apt_maintenance script only
        # where Python crashes (D-2) or serves what Rust refuses (D-4, D-5),
        # and then always with a JSON error, never a different 200 payload.
        cases = load("apt_state.json")["http"]["cases"]
        self.assertGreater(len(cases), 40)
        for case in cases:
            if case.get("python") == "crash" or "rust_status" in case:
                self.assertEqual(case["compare"], "rust_only", case["id"])
                self.assertIn(case["d"], {"D-2", "D-4", "D-5"}, case["id"])
                self.assertGreaterEqual(case["rust_status"], 500, case["id"])
                self.assertIn(
                    case["rust_error_type"],
                    {"invalid_json", "internal_error"},
                    case["id"],
                )
            else:
                self.assertIn(case["compare"], {"bytes", "error_type_only"}, case["id"])
                self.assertNotIn("d", case, case["id"])


class FloatFixture(unittest.TestCase):
    def test_size_and_file_limits(self) -> None:
        parts = sorted((FIXTURES / "float_repr").glob("part-*.txt"))
        self.assertTrue(parts)
        lines = 0
        for part in parts:
            # .pre-commit-config.yaml: check-added-large-files --maxkb=1000.
            self.assertLess(part.stat().st_size, 1000 * 1024, part.name)
            lines += sum(
                1
                for line in part.read_text(encoding="utf-8").splitlines()
                if not line.startswith("#")
            )
        # PLAN.md D-5: >= 100,000 random bit patterns plus the other cases.
        self.assertGreater(lines, 150_000)


class HtpasswdFixturesAreTestOnly(unittest.TestCase):
    def test_bcrypt_entries_use_cost_4(self) -> None:
        for name in ("htpasswd", "htpasswd-mixed", "htpasswd-invalid"):
            text = (FIXTURES / name).read_text(encoding="utf-8")
            self.assertTrue(text.startswith("# Test-only htpasswd file"), name)
            for match in re.finditer(r"\$2[abxy]\$(\d\d)\$", text):
                self.assertEqual(match.group(1), "04", name)


if __name__ == "__main__":
    unittest.main()
