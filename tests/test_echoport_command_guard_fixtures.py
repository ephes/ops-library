"""The Layer-1 fixtures of the Rust port of the Echoport remote command guard.

rust/echoport-command-guard/fixtures/ holds the Python guard's decisions,
generated by rust/echoport-command-guard/parity/gen_fixtures.py (PLAN.md 7.2).
The Rust guard is tested against them, so they must always describe the
guard and the runners as they are in this checkout:

- fixtures/GUARD_SHA256 names the guard file they were generated from (the
  Rust CI only runs for changes under rust/, so a guard change is caught here);
- regenerating them, including the recording of every runner's commands,
  gives byte-identical files;
- the contract the Rust prefilter relies on (PLAN.md 4.1): the Python guard
  accepts only printable ASCII and tab, and no runner sends `\\` or `#`.

After a change to the guard or a remote runner template: `just
echoport-command-guard-fixtures`, then update the Rust guard in the same change.
"""

from __future__ import annotations

import hashlib
import json
import random
import subprocess
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CRATE = ROOT / "rust" / "echoport-command-guard"
PARITY = CRATE / "parity"
FIXTURES = CRATE / "fixtures"
GUARD_PATH = ROOT / "roles" / "echoport_remote_command_guard" / "files" / "echoport-remote-command-guard.py"
REGENERATE = "regenerate with `just echoport-command-guard-fixtures` and update the Rust guard in the same change"

sys.path.insert(0, str(PARITY))
import gen_fixtures  # noqa: E402
import oracle  # noqa: E402


def read_jsonl(name: str) -> list[dict]:
    return gen_fixtures.read_jsonl(FIXTURES / name)


def manifest() -> dict:
    return json.loads((FIXTURES / "manifest.json").read_text(encoding="utf-8"))


def decision_cases() -> list[dict]:
    return [case for name in manifest()["decision_files"] for case in read_jsonl(name)]


def printable_ascii(command: str) -> bool:
    return all(c == "\t" or " " <= c <= "~" for c in command)


class FixturesMatchTheGuard(unittest.TestCase):
    def test_guard_sha256(self) -> None:
        recorded = (FIXTURES / "GUARD_SHA256").read_text(encoding="utf-8").strip()
        actual = hashlib.sha256(GUARD_PATH.read_bytes()).hexdigest()
        self.assertEqual(recorded, actual, f"the guard changed after the fixtures were generated: {REGENERATE}")

    def test_regenerating_gives_the_committed_fixtures(self) -> None:
        result = subprocess.run(
            [sys.executable, str(PARITY / "gen_fixtures.py"), "check", "--record"],
            capture_output=True, text=True, timeout=600, check=False,
        )
        self.assertEqual(result.returncode, 0, f"{result.stdout}{result.stderr}\n{REGENERATE}")

    def test_every_case_replays_from_its_env(self) -> None:
        """The env of a case is complete: its defaults reproduce the decision."""
        policies = {name: oracle.load_policy_ref(name) for name in ("production", "staging")}
        for case in decision_cases():
            command = oracle.decode_command(case)
            expected, _ = oracle.run_check(policies[case["policy"]], command, oracle.Scenario.from_env(case["env"]))
            if expected != case["expected"]:
                self.fail(f"{case['id']}: replays as {expected}")
        for case in read_jsonl("policy.jsonl"):
            data = bytes.fromhex(case["policy_hex"]) if "policy_hex" in case else case["policy_text"].encode()
            self.assertEqual(oracle.check_policy_bytes(data), case["expected"], case["id"])

    def test_case_ids_are_unique_and_allowed_differences_name_real_cases(self) -> None:
        ids = [case["id"] for case in decision_cases() + read_jsonl("policy.jsonl")]
        self.assertEqual(len(ids), len(set(ids)))
        allowed = json.loads((PARITY / "allowed_differences.json").read_text(encoding="utf-8"))
        for kind in ("python_versions", "rust"):
            for entry in allowed[kind]:
                self.assertIn(entry["id"], ids, entry)
                self.assertTrue(entry.get("reason"), entry)

    def test_manifest_lists_every_fixture_file(self) -> None:
        data = manifest()
        on_disk = sorted(str(p.relative_to(FIXTURES)) for p in FIXTURES.rglob("*.jsonl")
                         if p.relative_to(FIXTURES).parts[0] != "corpus")
        self.assertEqual(on_disk, sorted(data["decision_files"] + data["policy_files"]))
        for name in on_disk:
            self.assertEqual(data["cases"][name], len(read_jsonl(name)), name)
        # PLAN.md 7.2: about 10-20k generated cases.
        self.assertGreaterEqual(data["total"], 10_000)


class PrefilterContract(unittest.TestCase):
    """PLAN.md 4.1: the Rust guard may refuse `\\`, `#` and anything outside printable ASCII and tab."""

    def test_runners_and_journal_send_no_backslash_hash_or_odd_character(self) -> None:
        commands = [row["command"] for row in read_jsonl("corpus/runner.jsonl")]
        commands += [row["command"] for row in read_jsonl("journal.jsonl")]
        self.assertGreater(len(commands), 100)
        for command in commands:
            with self.subTest(command=command):
                self.assertTrue(printable_ascii(command))
                self.assertNotIn("\\", command)
                self.assertNotIn("#", command)
        for case in read_jsonl("runner.jsonl") + read_jsonl("journal.jsonl"):
            self.assertNotIn("p3", case, case["id"])

    def test_p3_tags_follow_the_prefilter_rule(self) -> None:
        for case in decision_cases():
            tags = set(case.get("p3", []))
            self.assertEqual(gen_fixtures.P3_PYTHON_ERROR in tags, case["expected"]["verdict"] == "error", case["id"])
            if "command_hex" in case:
                self.assertIn(gen_fixtures.P3_INVALID_UTF8, tags, case["id"])
                continue
            command = case["command"]
            hit = gen_fixtures.python_prechecks_pass(command) and gen_fixtures.prefilter_refuses(command)
            self.assertEqual(gen_fixtures.P3_PREFILTER in tags, hit, case["id"])

    def test_accepted_fixture_commands_are_printable_ascii(self) -> None:
        accepted = 0
        for case in decision_cases():
            if case["expected"]["verdict"] == "allowed":
                accepted += 1
                self.assertIn("command", case, case["id"])
                self.assertTrue(printable_ascii(case["command"]), case["id"])
        self.assertGreater(accepted, 1000)

    def test_python_accepts_only_printable_ascii_and_tab(self) -> None:
        """Random edits of accepted commands: whatever Python still accepts is printable ASCII and tab."""
        policies = {name: oracle.load_policy_ref(name) for name in ("production", "staging")}
        bases = [(row["policy"], row["command"]) for source in ("runner", "journal", "unit")
                 for row in read_jsonl(f"{source}.jsonl") if row["expected"]["verdict"] == "allowed"]
        rng = random.Random(20261021)
        weighted = " \t'\"\\#$;&|`()<>*?~=-_./:@0aZ"
        special = "\x00\x01\x0b\x0c\x1b\x1c\x1d\x1e\x1f\x7f\x85\xa0\u1680\u2000\u200b\u2028\u2029\u202f\u3000\ufeff"

        def char() -> str:
            pick = rng.random()
            if pick < 0.35:
                return rng.choice(weighted)
            if pick < 0.6:
                return rng.choice(special)
            if pick < 0.8:
                return chr(rng.randrange(0x00, 0x80))
            while True:
                code = rng.randrange(0x80, 0x110000)
                if not 0xD800 <= code <= 0xDFFF:
                    return chr(code)

        accepted = 0
        for _ in range(4000):
            policy, command = rng.choice(bases)
            for _ in range(rng.randint(1, 3)):
                at = rng.randrange(len(command) + 1)
                edit = rng.random()
                if edit < 0.6:
                    command = command[:at] + char() + command[at:]
                elif edit < 0.9 and at < len(command):
                    command = command[:at] + char() + command[at + 1:]
                elif at < len(command):
                    command = command[:at] + command[at + 1:]
            expected, _ = oracle.run_check(policies[policy], command, gen_fixtures.runner_view())
            if expected["verdict"] == "allowed":
                accepted += 1
                self.assertTrue(printable_ascii(command), f"Python accepts {command!r}")
        self.assertGreater(accepted, 50, "the property test exercised too few accepted commands")


class OracleServer(unittest.TestCase):
    """parity/oracle.py as the Rust property tests call it (JSON lines)."""

    def ask(self, *requests: dict) -> list[dict]:
        lines = "".join(json.dumps(r) + "\n" for r in requests)
        result = subprocess.run([sys.executable, "-I", str(PARITY / "oracle.py")], input=lines,
                                capture_output=True, text=True, timeout=60, check=False)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stderr, "")
        return [json.loads(line) for line in result.stdout.splitlines()]

    def test_round_trip(self) -> None:
        case = next(c for c in read_jsonl("fs.jsonl") if c["env"]["users"])
        ping, check, inline, split, broken, policy, bad, link, loop, real, odd = self.ask(
            {"op": "ping", "id": 1},
            {"op": "check", "id": 2, "policy_ref": case["policy"], "command": case["command"], "env": case["env"]},
            {"op": "check", "policy": {"units": ["x.service"]}, "command": "systemctl start x.service"},
            {"op": "split", "command": "a \"b c\"d ''"},
            {"op": "split", "command": "a 'b"},
            {"op": "check_policy", "text": "{\"units\": \"abc\"}"},
            {"op": "check_policy", "hex": "ff"},
            {"op": "realpath", "path": "/a/link/x/../y",
             "fs": {"/a": {"kind": "dir", "mode": 0o755, "uid": 0, "nlink": 2},
                    "/a/link": {"kind": "lnk", "mode": 0o777, "uid": 0, "nlink": 1, "target": "../b"},
                    "/b": {"kind": "dir", "mode": 0o755, "uid": 0, "nlink": 2}}},
            {"op": "realpath", "path": "/l1/x",
             "fs": {"/l1": {"kind": "lnk", "mode": 0o777, "uid": 0, "nlink": 1, "target": "/l2"},
                    "/l2": {"kind": "lnk", "mode": 0o777, "uid": 0, "nlink": 1, "target": "/l1"}}},
            {"op": "os_realpath", "path": "/"},
            {"op": "nope", "id": "x"},
        )
        self.assertEqual((ping["ok"], ping["id"], ping["guard_sha256"]), (True, 1, oracle.guard_sha256()))
        self.assertEqual((check["id"], check["expected"], check["env"]), (2, case["expected"], case["env"]))
        self.assertEqual(inline["expected"]["argv"], ["systemctl", "start", "x.service"])
        self.assertEqual(split["tokens"], ["a", "b cd", ""])
        self.assertEqual(broken["error"], "No closing quotation")
        self.assertEqual(policy["expected"]["normalized"]["units"], ["a", "b", "c"])
        self.assertEqual((bad["expected"]["ok"], bad["expected"]["error_type"]), (False, "UnicodeDecodeError"))
        self.assertEqual(link["resolved"], "/b/y")
        self.assertTrue(loop["ok"])
        self.assertTrue(loop["resolved"].startswith("/l"))
        self.assertEqual(real["resolved"], "/")
        self.assertEqual((odd["ok"], odd["id"]), (False, "x"))


if __name__ == "__main__":
    unittest.main()
